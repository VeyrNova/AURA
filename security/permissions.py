# Permissions enabled by default. v0.7.0 adds WEB_READ for controlled network tools;
# process/system/secret capabilities remain disabled.
DEFAULT_GRANTED_PERMISSIONS: frozenset[Permission] = frozenset(
    {
        Permission.READ_LOCAL_DATA,
        Permission.WRITE_LOCAL_DATA,
        Permission.DELETE_LOCAL_RECORDS,
        # P0.6.2.8 permits only SystemService's fixed safe-app allowlist.
        # It does NOT grant PROCESS_CONTROL and therefore cannot authorize
        # arbitrary RUN_PROGRAM operations.
        Permission.SAFE_APP_LAUNCH,
        Permission.AUTHORIZED_FOLDER_ACCESS,
        Permission.AUTHORIZED_FILE_READ,
        # v0.7.0 grants read-only external network access to deterministic tools.
        # High-risk network actions (e.g. SEND_EMAIL) still require confirmation.
        Permission.WEB_READ,
    }
)

