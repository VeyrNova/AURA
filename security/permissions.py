"""Permissions and action policies for AURA v0.7.0.

The LLM never grants these permissions. Policies are owned by deterministic code.
"""
from dataclasses import dataclass
from enum import Enum

from security.risk import RiskLevel


class Permission(str, Enum):
    READ_LOCAL_DATA = "read_local_data"
    WRITE_LOCAL_DATA = "write_local_data"
    DELETE_LOCAL_RECORDS = "delete_local_records"
    FILESYSTEM_DELETE = "filesystem_delete"
    EXTERNAL_NETWORK = "external_network"
    WEB_READ = "web_read"
    BROWSER_MUTATE = "browser_mutate"
    BROWSER_DOWNLOAD = "browser_download"
    LOCATION_ACCESS = "location_access"
    # P0.6.2.8 — separate allowlisted app launch from arbitrary process control.
    SAFE_APP_LAUNCH = "safe_app_launch"
    # P0.6.5.1 — scoped access to the explicit authorized-folder registry.
    AUTHORIZED_FOLDER_ACCESS = "authorized_folder_access"
    # P0.6.5.2 — content read is separate from folder open/list permissions.
    AUTHORIZED_FILE_READ = "authorized_file_read"
    PROCESS_CONTROL = "process_control"
    SYSTEM_CHANGE = "system_change"
    SECRET_ACCESS = "secret_access"


@dataclass(frozen=True)
class ActionPolicy:
    risk: RiskLevel
    permission: Permission
    confirmation_required: bool = False


